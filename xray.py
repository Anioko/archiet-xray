"""Archiet X-Ray — see the architecture your AI is flying blind without.

Point it at any repo. It extracts the *actual* architecture — routes, domain
entities, async tasks, module dependencies, boundary risks — into:

  - architecture.json   machine-readable model (the "repo genome")
  - ARCHITECTURE.md     human-readable map with Mermaid diagrams
  - AGENT_CONTEXT.md    compact context pack for AI coding agents

Philosophy (borrowed from microcodegen): this file is the complete algorithm.
Stdlib only. No LLM calls — every fact in the output is deterministically
extracted from source, so the same repo always produces the same map. What we
cannot extract with confidence is labelled "unmapped", never guessed.

Usage:
    python xray.py [REPO_PATH] [--out DIR] [--json] [--quiet]

Generated by the Archiet project — https://archiet.com
"""

