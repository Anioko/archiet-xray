def mermaid_module_graph(edges: dict[tuple[str, str], int], cap: int = 18) -> str:
    weight: dict[str, int] = defaultdict(int)
    for (a, b), n in edges.items():
        weight[a] += n
        weight[b] += n
    keep = set(sorted(weight, key=weight.get, reverse=True)[:cap])
    ids = {m: f"M{i}" for i, m in enumerate(sorted(keep))}
    lines = ["```mermaid", "graph LR"]
    for m in sorted(keep):
        lines.append(f'  {ids[m]}["{m}"]')
    for (a, b), n in sorted(edges.items(), key=lambda kv: -kv[1]):
        if a in keep and b in keep and a != b:
            lines.append(f"  {ids[a]} -->|{n}| {ids[b]}")
    lines.append("```")
    return "\n".join(lines)


def mermaid_er(entities: list[Entity], cap: int = 20) -> str:
    ents = entities[:cap]
    names = {e.name for e in ents}
    lines = ["```mermaid", "erDiagram"]
    for e in ents:
        lines.append(f"  {e.name} {{ }}")
    seen = set()
    for e in ents:
        for r in e.relations:
            tgt = next(
                (
                    n
                    for n in names
                    if n.lower() == r.lower().rstrip("s") or n.lower() == r.lower()
                ),
                None,
            )
            if tgt and (e.name, tgt) not in seen and e.name != tgt:
                seen.add((e.name, tgt))
                lines.append(f"  {e.name} }}o--|| {tgt} : refs")
    lines.append("```")
    return "\n".join(lines)


