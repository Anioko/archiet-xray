def gitignored_dirs(root: Path) -> set[str]:
    """Top-level directory names ignored by a simple .gitignore (best effort)."""
    out: set[str] = set()
    gi = root / ".gitignore"
    if not gi.is_file():
        return out
    for line in gi.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "!")):
            continue
        name = line.strip("/")
        if name and "*" not in name and "/" not in name:
            out.add(name)
    return out


def walk_repo(root: Path) -> list[Path]:
    files: list[Path] = []
    skip = SKIP_DIRS | gitignored_dirs(root)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in skip and not d.startswith(".")]
        for fn in filenames:
            p = Path(dirpath) / fn
            if p.suffix.lower() in CODE_EXTS:
                try:
                    if p.stat().st_size <= MAX_FILE_BYTES:
                        files.append(p)
                except OSError:
                    continue
    return files


