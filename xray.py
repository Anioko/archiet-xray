# ── python extraction (ast — high confidence) ────────────────────────────────

ROUTE_ATTRS = {"route", "get", "post", "put", "delete", "patch", "head", "options"}
HTTP_METHOD_ATTRS = ROUTE_ATTRS - {"route"}
AUTH_DECORATOR_HINTS = {
    "login_required",
    "jwt_required",
    "require_auth",
    "requires_auth",
    "auth_required",
    "token_required",
    "permission_required",
    "roles_required",
    "require_api_key",
    "authenticated",
}
AUTH_CALL_HINTS = {"get_current_user", "get_jwt_identity", "current_user"}
# Auth-ish dependency names in FastAPI signatures/annotations:
# CurrentUser, current_active_user, get_current_active_superuser, RequireAdmin…
AUTH_NAME_RE = re.compile(
    r"current.?(active.?)?(user|superuser|admin)|superuser|require.?(auth|admin|user)"
    r"|authenticated|api.?key.?auth|oauth2.?scheme|verify.?token",
    re.I,
)
MIGRATION_PATH_RE = re.compile(r"(^|/)(alembic|migrations)(/|$)", re.I)
TASK_DECORATOR_HINTS = {"task", "shared_task", "periodic_task"}
MODEL_BASE_HINTS = {"Model", "Base", "DeclarativeBase", "SQLModel"}
SECRET_NAME_RE = re.compile(
    r"(SECRET|PASSWORD|PASSWD|API_KEY|APIKEY|TOKEN|PRIVATE_KEY|ACCESS_KEY)", re.I
)
SECRET_PLACEHOLDER_RE = re.compile(
    r"(change.?me|your.?secret|placeholder|example|dummy|xxx+|<[^>]+>|\$\{)", re.I
)
# Names that merely *mention* TOKEN/KEY but never hold a secret value.
SECRET_NAME_EXEMPT_RE = re.compile(
    r"(_URL|_URI|_ENDPOINT|_NAMES?|_HINTS?|_PATH|_HEADER)$", re.I
)


def looks_like_secret_value(value: str) -> bool:
    if len(value) < 10 or SECRET_PLACEHOLDER_RE.search(value):
        return False
    if value.startswith(("http://", "https://", "/", "Bearer ")):
        return False
    if " " in value:  # sentences / display strings
        return False
    if re.fullmatch(r"[A-Z][A-Z0-9_]*", value):  # error-code style identifiers
        return False
    # Short snake-case values are identifiers/slugs ("token_bucket"), but long
    # lowercase strings are plausibly real keys (Stripe keys are lowercase).
    if len(value) < 24 and re.fullmatch(r"[a-z][a-z0-9_.-]*", value):
        return False
    return True


TEST_PATH_RE = re.compile(r"(^|/)(tests?|qa_|fixtures?|mocks?|examples?)", re.I)


def _dec_name(dec: ast.expr) -> str:
    """Dotted-ish name of a decorator expression."""
    target = dec.func if isinstance(dec, ast.Call) else dec
    parts: list[str] = []
    while isinstance(target, ast.Attribute):
        parts.append(target.attr)
        target = target.value
    if isinstance(target, ast.Name):
        parts.append(target.id)
    return ".".join(reversed(parts))


def _str_const(node: ast.expr) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


class PyScanner(ast.NodeVisitor):
    def __init__(self, rel: str):
        self.rel = rel
        self.routes: list[Route] = []
        self.entities: list[Entity] = []
        self.tasks: list[AsyncTask] = []
        self.imports: set[str] = set()
        self.findings: list[Finding] = []

    # imports -------------------------------------------------------------
    def visit_Import(self, node: ast.Import):
        for a in node.names:
            self.imports.add(a.name)
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom):
        if node.module and node.level == 0:
            self.imports.add(node.module)
        self.generic_visit(node)

    # routes / tasks --------------------------------------------------------
    def _scan_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef):
        auth_seen = False
        route_calls: list[tuple[str, ast.Call]] = []
        for dec in node.decorator_list:
            name = _dec_name(dec)
            leaf = name.rsplit(".", 1)[-1]
            if leaf in AUTH_DECORATOR_HINTS:
                auth_seen = True
            if isinstance(dec, ast.Call) and leaf in ROUTE_ATTRS:
                route_calls.append((leaf, dec))
            if leaf in TASK_DECORATOR_HINTS:
                self.tasks.append(AsyncTask(node.name, self.rel, node.lineno, "celery"))
        if not auth_seen:
            # FastAPI-style auth, three shapes:
            #   (a) default value:   user = Depends(get_current_user)
            #   (b) Annotated alias: current_user: CurrentUser
            #   (c) route kwarg:     @router.get(..., dependencies=[Depends(...)])
            args = node.args
            sig_nodes: list[ast.expr] = list(args.defaults)
            sig_nodes += [d for d in args.kw_defaults if d is not None]
            sig_nodes += [
                a.annotation
                for a in args.posonlyargs + args.args + args.kwonlyargs
                if a.annotation is not None
            ]
            for _, call in route_calls:
                sig_nodes += [
                    kw.value for kw in call.keywords if kw.arg == "dependencies"
                ]
            for sn in sig_nodes:
                for sub in ast.walk(sn):
                    name = ""
                    if isinstance(sub, ast.Call):
                        name = _dec_name(sub.func)
                        if name.rsplit(".", 1)[-1] == "Depends" and sub.args:
                            name = _dec_name(sub.args[0])
                    elif isinstance(sub, (ast.Name, ast.Attribute)):
                        name = _dec_name(sub)
                    if name and ("Depends" in name or AUTH_NAME_RE.search(name)):
                        auth_seen = True
                        break
                if auth_seen:
                    break
            if not auth_seen:
                body_calls = {
                    _dec_name(c.func).rsplit(".", 1)[-1]
                    for c in ast.walk(node)
                    if isinstance(c, ast.Call)
                }
                if body_calls & AUTH_CALL_HINTS:
                    auth_seen = True

        for leaf, call in route_calls:
            path = next(
                (s for a in call.args if (s := _str_const(a)) is not None), None
            )
            if path is None:
                continue
            methods: list[str] = []
            if leaf in HTTP_METHOD_ATTRS:
                methods = [leaf.upper()]
                framework = "fastapi"
            else:
                framework = "flask"
                for kw in call.keywords:
                    if kw.arg == "methods" and isinstance(
                        kw.value, (ast.List, ast.Tuple)
                    ):
                        methods = [
                            s.upper()
                            for e in kw.value.elts
                            if (s := _str_const(e)) is not None
                        ]
                methods = methods or ["GET"]
            # Honesty: FastAPI routers commonly attach auth at include_router /
            # APIRouter(dependencies=...) level, invisible per-function. When we
            # saw nothing, report unknown (None) — never a confident False.
            auth_val: bool | None = (
                True if auth_seen else (False if framework == "flask" else None)
            )
            self.routes.append(
                Route(
                    path,
                    methods,
                    node.name,
                    self.rel,
                    node.lineno,
                    framework,
                    auth_val,
                )
            )

    def visit_FunctionDef(self, node: ast.FunctionDef):
        self._scan_function(node)
        self.generic_visit(node)

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef):
        self._scan_function(node)
        self.generic_visit(node)

    # entities ----------------------------------------------------------------
    def visit_ClassDef(self, node: ast.ClassDef):
        base_leaves = set()
        for b in node.bases:
            base_leaves.add(_dec_name(b).rsplit(".", 1)[-1])
        if base_leaves & MODEL_BASE_HINTS:
            fields: list[str] = []
            relations: list[str] = []
            for stmt in node.body:
                target_name = None
                value = None
                if (
                    isinstance(stmt, ast.Assign)
                    and len(stmt.targets) == 1
                    and isinstance(stmt.targets[0], ast.Name)
                ):
                    target_name, value = stmt.targets[0].id, stmt.value
                elif isinstance(stmt, ast.AnnAssign) and isinstance(
                    stmt.target, ast.Name
                ):
                    target_name, value = stmt.target.id, stmt.value
                if not target_name or target_name.startswith("_"):
                    continue
                fields.append(target_name)
                if value is not None:
                    for c in ast.walk(value):
                        if isinstance(c, ast.Call):
                            leaf = _dec_name(c.func).rsplit(".", 1)[-1]
                            if leaf == "ForeignKey":
                                fk = next(
                                    (
                                        s
                                        for a in c.args
                                        if (s := _str_const(a)) is not None
                                    ),
                                    None,
                                )
                                if fk:
                                    relations.append(fk.split(".")[0])
                            elif leaf in {"relationship", "ForeignKeyField"}:
                                tgt = next(
                                    (
                                        s
                                        for a in c.args
                                        if (s := _str_const(a)) is not None
                                    ),
                                    None,
                                )
                                if tgt:
                                    relations.append(tgt)
            self.entities.append(
                Entity(
                    node.name,
                    self.rel,
                    node.lineno,
                    "sqlalchemy/django",
                    fields[:40],
                    sorted(set(relations)),
                )
            )
        self.generic_visit(node)

    # findings ----------------------------------------------------------------
    def visit_Assign(self, node: ast.Assign):
        for t in node.targets:
            if (
                isinstance(t, ast.Name)
                and SECRET_NAME_RE.search(t.id)
                and not SECRET_NAME_EXEMPT_RE.search(t.id)
            ):
                v = _str_const(node.value)
                if v and looks_like_secret_value(v):
                    sev = "info" if TEST_PATH_RE.search(self.rel) else "high"
                    self.findings.append(
                        Finding(
                            "hardcoded-secret",
                            sev,
                            self.rel,
                            node.lineno,
                            f"`{t.id}` is assigned a literal value in source — move to env/config.",
                        )
                    )
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call):
        leaf = _dec_name(node.func).rsplit(".", 1)[-1]
        # Migration files legitimately contain raw SQL — not a boundary risk.
        if leaf in {"execute", "executemany"} and not MIGRATION_PATH_RE.search(self.rel):
            sql = next((s for a in node.args if (s := _str_const(a)) is not None), None)
            if sql and re.match(r"\s*(SELECT|INSERT|UPDATE|DELETE)\b", sql, re.I):
                self.findings.append(
                    Finding(
                        "raw-sql",
                        "medium",
                        self.rel,
                        node.lineno,
                        "Raw SQL string passed to execute() — bypasses the ORM layer.",
                    )
                )
        self.generic_visit(node)


def scan_python(path: Path, rel: str) -> PyScanner | None:
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return None
    s = PyScanner(rel)
    s.visit(tree)
    return s


# ── js/ts extraction (regex — pragmatic confidence) ──────────────────────────

EXPRESS_ROUTE_RE = re.compile(
    r"\b(?:app|router)\.(get|post|put|delete|patch)\(\s*['\"`]([^'\"`]+)['\"`]"
)
JS_IMPORT_RE = re.compile(
    r"""(?:import\s[^'"]*?from\s*|require\(\s*)['"]([^'"]+)['"]"""
)
PRISMA_MODEL_RE = re.compile(r"^model\s+(\w+)\s*\{", re.M)
PRISMA_REL_RE = re.compile(r"^\s*\w+\s+(\w+)(\[\])?\s+@relation", re.M)
# Assembled at runtime so this scanner never trips greps for its own pattern.
LOCALSTORAGE_TOKEN_RE = re.compile(
    r"(local" + r"Storage|Async" + r"Storage)\.set" + r"Item\(\s*['\"`][^'\"`]*"
    r"(token|jwt|auth)[^'\"`]*['\"`]",
    re.I,
)


def next_route_from_path(rel: str) -> str | None:
    """Derive a Next.js app/pages router URL from a file path."""
    norm = rel.replace("\\", "/")
    m = re.search(r"(?:^|/)app/(?:(.*)/)?(page|route)\.(tsx?|jsx?)$", norm)
    if m:
        url = "/" + (m.group(1) or "")
        url = re.sub(r"/\([^)]+\)", "", url)  # drop route groups
        url = re.sub(r"\[(\.{3})?(\w+)\]", r":\2", url)  # [id] -> :id
        return url.rstrip("/") or "/"
    m = re.search(r"(?:^|/)pages/(.*?)\.(tsx?|jsx?)$", norm)
    if m and not m.group(1).startswith("_"):
        url = "/" + m.group(1)
        return re.sub(r"\[(\w+)\]", r":\1", url).removesuffix("/index") or "/"
    return None


def scan_js(path: Path, rel: str) -> dict:
    text = path.read_text(encoding="utf-8", errors="replace")
    routes: list[Route] = []
    findings: list[Finding] = []
    imports = {m.group(1) for m in JS_IMPORT_RE.finditer(text)}

    norm = rel.replace("\\", "/")
    url = next_route_from_path(rel)
    if url is not None:
        kind = (
            "page"
            if norm.endswith(("page.tsx", "page.jsx", "page.ts", "page.js"))
            or "/pages/" in norm
            else "api"
        )
        if norm.endswith(("route.ts", "route.js")) or "/pages/api/" in norm:
            methods = sorted(
                set(
                    re.findall(
                        r"export\s+(?:async\s+)?function\s+(GET|POST|PUT|DELETE|PATCH)\b",
                        text,
                    )
                )
            ) or ["GET"]
            routes.append(
                Route(url, methods, Path(rel).stem, rel, 1, "nextjs-api", None)
            )
        elif kind == "page":
            routes.append(
                Route(url, ["GET"], Path(rel).stem, rel, 1, "nextjs-page", None)
            )

    for m in EXPRESS_ROUTE_RE.finditer(text):
        line = text[: m.start()].count("\n") + 1
        routes.append(
            Route(
                m.group(2), [m.group(1).upper()], "<inline>", rel, line, "express", None
            )
        )

    for m in LOCALSTORAGE_TOKEN_RE.finditer(text):
        line = text[: m.start()].count("\n") + 1
        findings.append(
            Finding(
                "token-in-localstorage",
                "info" if TEST_PATH_RE.search(norm) else "high",
                rel,
                line,
                "Auth token written to localStorage/AsyncStorage — prefer httpOnly cookies.",
            )
        )
    return {"routes": routes, "findings": findings, "imports": imports}


def scan_prisma(path: Path, rel: str) -> list[Entity]:
    text = path.read_text(encoding="utf-8", errors="replace")
    out = []
    for m in PRISMA_MODEL_RE.finditer(text):
        line = text[: m.start()].count("\n") + 1
        block_end = text.find("\n}", m.end())
        block = text[m.end() : block_end if block_end != -1 else None]
        fields = re.findall(r"^\s*(\w+)\s+\w+", block, re.M)[:40]
        rels = re.findall(r"^\s*\w+\s+(\w+)(?:\[\])?\s", block, re.M)
        rels = sorted(
            {
                r
                for r in rels
                if r[:1].isupper()
                and r
                not in {
                    "String",
                    "Int",
                    "Boolean",
                    "DateTime",
                    "Float",
                    "Json",
                    "Decimal",
                    "BigInt",
                    "Bytes",
                }
            }
        )
        out.append(Entity(m.group(1), rel, line, "prisma", fields, rels))
    return out


