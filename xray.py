def xray(root: Path) -> dict:
    root = root.resolve()
    files = walk_repo(root)
    routes: list[Route] = []
    entities: list[Entity] = []
    tasks: list[AsyncTask] = []
    findings: list[Finding] = []
    file_imports: dict[str, set[str]] = {}
    mapped: set[str] = set()
    parsed: set[str] = set()

    for p in files:
        rel = str(p.relative_to(root)).replace("\\", "/")
        if p.suffix == ".py":
            s = scan_python(p, rel)
            if s is None:
                continue
            parsed.add(rel)
            if s.routes or s.entities or s.tasks:
                mapped.add(rel)
            routes += s.routes
            entities += s.entities
            tasks += s.tasks
            findings += s.findings
            file_imports[rel] = s.imports
        elif p.suffix in {".ts", ".tsx", ".js", ".jsx"}:
            r = scan_js(p, rel)
            parsed.add(rel)
            if r["routes"]:
                mapped.add(rel)
            routes += r["routes"]
            findings += r["findings"]
            file_imports[rel] = r["imports"]
        elif p.suffix == ".prisma":
            es = scan_prisma(p, rel)
            parsed.add(rel)
            if es:
                mapped.add(rel)
            entities += es

    # module graph — resolve imports against real Python package roots
    # (handles backend/app, src/<pkg> nesting) plus plain top-level dirs.
    pkg_roots = python_package_roots(files, root)
    top_levels = {
        Path(rel).parts[0] for rel in file_imports if len(Path(rel).parts) > 1
    }

    def src_module(rel: str) -> str:
        for name, prefix in pkg_roots.items():
            if rel == prefix or rel.startswith(prefix + "/"):
                return name
        return rel.split("/")[0] if "/" in rel else "(root)"

    edges: dict[tuple[str, str], int] = defaultdict(int)
    fan_in: dict[str, int] = defaultdict(int)
    fan_out: dict[str, int] = defaultdict(int)
    for rel, imps in file_imports.items():
        src = src_module(rel)
        for imp in imps:
            head = imp.lstrip("./").replace("\\", "/").split("/")[0].split(".")[0]
            tgt = head if head in pkg_roots else internal_target(imp, top_levels)
            if tgt and tgt != src:
                edges[(src, tgt)] += 1
    for (a, b), n in edges.items():
        fan_out[a] += n
        fan_in[b] += n

    # files importing a module also make 2-segment modules hot
    importable = set(pkg_roots) | top_levels
    seg2_in: dict[str, int] = defaultdict(int)
    for rel, imps in file_imports.items():
        for imp in imps:
            norm = imp.replace(".", "/").lstrip("/")
            parts = norm.split("/")
            if len(parts) >= 2 and parts[0] in importable:
                seg2_in["/".join(parts[:2])] += 1
    hotspots = [
        {"module": m, "fan_in": n, "fan_out": fan_out.get(m.split("/")[0], 0)}
        for m, n in sorted(seg2_in.items(), key=lambda kv: -kv[1])
    ]

    stats = {
        "code_files": len(files),
        "parsed_files": len(parsed),
        "mapped_files": len(mapped),
        "unmapped_files": len(files) - len(parsed),
        "routes": len(routes),
        "entities": len(entities),
        "tasks": len(tasks),
        "graph_edges": len(edges),
    }
    model = {
        "xray_version": XRAY_VERSION,
        "repo": root.name,
        "stats": stats,
        "score": visibility_score(stats),
        "modules": sorted(top_levels),
        "routes": [asdict(r) for r in sorted(routes, key=lambda r: r.path)],
        "entities": [asdict(e) for e in sorted(entities, key=lambda e: e.name)],
        "tasks": [asdict(t) for t in tasks],
        "findings": [
            asdict(f)
            for f in sorted(findings, key=lambda f: (f.severity != "high", f.file))
        ],
        "module_edges": [
            {"from": a, "to": b, "imports": n}
            for (a, b), n in sorted(edges.items(), key=lambda kv: -kv[1])
        ],
        "hotspots": hotspots,
    }
    model["mermaid_modules"] = mermaid_module_graph(edges)
    model["mermaid_er"] = mermaid_er(entities)
    return model


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Archiet X-Ray — extract the real architecture of a repo."
    )
    ap.add_argument("path", nargs="?", default=".", help="repo root (default: cwd)")
    ap.add_argument("--out", default=None, help="output dir (default: <repo>/.archiet)")
    ap.add_argument(
        "--json", action="store_true", help="print architecture.json to stdout"
    )
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    root = Path(args.path)
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 2
    model = xray(root)

    out_dir = Path(args.out) if args.out else root / ".archiet"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "architecture.json").write_text(
        json.dumps(model, indent=2), encoding="utf-8"
    )
    (out_dir / "ARCHITECTURE.md").write_text(
        render_architecture_md(model), encoding="utf-8"
    )
    (out_dir / "AGENT_CONTEXT.md").write_text(
        render_agent_context(model), encoding="utf-8"
    )

    if args.json:
        print(json.dumps(model, indent=2))
    elif not args.quiet:
        s = model["stats"]
        print(f"Archiet X-Ray v{XRAY_VERSION} — {model['repo']}")
        print(f"  visibility score : {model['score']}/100")
        print(f"  code files       : {s['code_files']} ({s['mapped_files']} mapped)")
        print(f"  routes           : {s['routes']}")
        print(f"  entities         : {s['entities']}")
        print(f"  async tasks      : {s['tasks']}")
        print(f"  findings         : {len(model['findings'])}")
        print(f"  wrote            : {out_dir / 'ARCHITECTURE.md'}")
        print(f"                     {out_dir / 'AGENT_CONTEXT.md'}")
        print(f"                     {out_dir / 'architecture.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
